import React, { useEffect, useState } from "react";
import { AlertTriangle, ExternalLink, RefreshCw } from "lucide-react";
import { Link } from "react-router-dom";
import PageHeader from "../components/common/PageHeader";
import Button from "../components/common/Button";
import Badge from "../components/common/Badge";
import Loading from "../components/common/Loading";
import EmptyState from "../components/common/EmptyState";
import { getAlerts, updateAlertStatus } from "../services/alertService";
import { formatDate } from "../utils/formatters";

export default function Alerts() {
    const [alerts, setAlerts] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState("");
    const [updating, setUpdating] = useState("");

    const loadAlerts = async () => {
        try {
            setError("");
            setAlerts(await getAlerts({ limit: 100 }));
        } catch (requestError) {
            setError(requestError.friendlyMessage || "Unable to load alerts.");
        } finally {
            setLoading(false);
        }
    };

    useEffect(() => { void loadAlerts(); }, []);

    const setStatus = async (alert, status) => {
        const key = `${alert.email_id}:${alert.source}`;
        try {
            setUpdating(key);
            setError("");
            await updateAlertStatus(alert.email_id, alert.source, status);
            await loadAlerts();
        } catch (requestError) {
            setError(requestError.friendlyMessage || "Unable to update alert.");
        } finally {
            setUpdating("");
        }
    };

    return (
        <div>
            <PageHeader title="Alerts" description="Risk alerts generated by email analysis." >
                <Button variant="secondary" onClick={() => { setLoading(true); void loadAlerts(); }} disabled={loading}><RefreshCw className="h-4 w-4" />Refresh</Button>
            </PageHeader>
            {error && <div className="mb-4 rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700" role="alert">{error}</div>}
            <section className="card overflow-hidden">
                <div className="card-header"><div><h2 className="text-sm font-semibold text-slate-900">Recent alerts</h2><p className="mt-1 text-xs text-slate-500">Showing up to 100 most recent alerts</p></div><Badge variant="neutral">{alerts.length}</Badge></div>
                {loading ? <Loading text="Loading alerts..." /> : alerts.length === 0 ? <EmptyState title="No alerts" description="Risk alerts appear here when an analysis reaches the configured threshold." /> : (
                    <div className="overflow-x-auto">
                        <table className="w-full min-w-[720px] text-left">
                            <thead className="bg-slate-50 text-xs uppercase tracking-wide text-slate-500"><tr><th className="px-5 py-3">Alert</th><th className="px-5 py-3">Risk</th><th className="px-5 py-3">Case</th><th className="px-5 py-3">Created</th><th className="px-5 py-3">Status</th><th className="px-5 py-3" /></tr></thead>
                            <tbody className="divide-y divide-slate-100">{alerts.map((alert, index) => <tr key={`${alert.email_id}-${alert.source || "alert"}-${index}`} className="hover:bg-slate-50">
                                <td className="px-5 py-4"><div className="flex items-center gap-2"><AlertTriangle className="h-4 w-4 shrink-0 text-orange-600" /><div><p className="text-sm font-medium text-slate-800">{alert.verdict || "Risk alert"}</p><Link to={`/emails/${encodeURIComponent(alert.email_id)}`} className="mt-1 block font-mono text-xs text-blue-700 hover:underline">{alert.email_id}</Link></div></div></td>
                                <td className="px-5 py-4"><div className="flex items-center gap-2"><Badge variant={String(alert.severity || "low").toLowerCase()}>{alert.severity || "UNKNOWN"}</Badge><span className="text-xs text-slate-600">{alert.score ?? "—"}/100</span></div></td>
                                <td className="px-5 py-4">{alert.case_id ? <Link to={`/cases?case=${encodeURIComponent(alert.case_id)}`} className="text-xs text-blue-700 hover:underline">{alert.case_id}</Link> : <span className="text-xs text-slate-400">—</span>}</td>
                                <td className="px-5 py-4 text-xs text-slate-500">{formatDate(alert.created_at)}</td>
                                <td className="px-5 py-4"><Badge variant={String(alert.status || "OPEN").toLowerCase() === "open" ? "warning" : "neutral"}>{alert.status || "UNKNOWN"}</Badge></td>
                                <td className="px-5 py-4"><div className="flex items-center gap-3">{String(alert.status).toUpperCase() === "OPEN" && <Button variant="secondary" disabled={updating === `${alert.email_id}:${alert.source}`} onClick={() => void setStatus(alert, "ACKNOWLEDGED")}>Acknowledge</Button>}{String(alert.status).toUpperCase() === "ACKNOWLEDGED" && <Button variant="secondary" disabled={updating === `${alert.email_id}:${alert.source}`} onClick={() => void setStatus(alert, "RESOLVED")}>Resolve</Button>}{String(alert.status).toUpperCase() === "RESOLVED" && <Button variant="secondary" disabled={updating === `${alert.email_id}:${alert.source}`} onClick={() => void setStatus(alert, "OPEN")}>Reopen</Button>}<Link aria-label="Open email" to={`/emails/${encodeURIComponent(alert.email_id)}`} className="text-slate-500 hover:text-blue-700"><ExternalLink className="h-4 w-4" /></Link></div></td>
                            </tr>)}</tbody>
                        </table>
                    </div>
                )}
            </section>
        </div>
    );
}
